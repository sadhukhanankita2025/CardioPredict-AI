import { useEffect, useState } from "react";

import {
  ClipboardList,
  Download,
  FileText,
  HeartPulse,
  Search,
} from "lucide-react";

import jsPDF from "jspdf";

import {
  getPredictionHistory,
  type PredictionRecord,
} from "../utils/predictionStorage";

function Reports() {
  const [reports, setReports] = useState<PredictionRecord[]>([]);
  const [search, setSearch] = useState("");

  useEffect(() => {
    setReports(getPredictionHistory());
  }, []);

  const filteredReports = reports.filter((report) =>
    report.patientName
      .toLowerCase()
      .includes(search.toLowerCase()),
  );

  const generatePDF = (report: PredictionRecord) => {
    const pdf = new jsPDF();

    const margin = 20;
    let y = 20;

    // Title
    pdf.setFontSize(20);
    pdf.setFont("helvetica", "bold");
    pdf.text("CardioPredict-AI", margin, y);

    y += 10;

    pdf.setFontSize(15);
    pdf.text("Cardiac Risk Prediction Report", margin, y);

    y += 15;

    // Patient
    pdf.setFontSize(11);
    pdf.setFont("helvetica", "bold");
    pdf.text("Patient Information", margin, y);

    y += 8;

    pdf.setFont("helvetica", "normal");

    pdf.text(
      `Patient Name: ${report.patientName}`,
      margin,
      y,
    );

    y += 7;

    pdf.text(
      `Date: ${report.date}`,
      margin,
      y,
    );

    y += 7;

    pdf.text(
      `Time: ${report.time}`,
      margin,
      y,
    );

    y += 12;

    // Parameters
    pdf.setFont("helvetica", "bold");
    pdf.text("Clinical Parameters", margin, y);

    y += 8;

    pdf.setFont("helvetica", "normal");

    const parameters = [
      ["Age", report.age],
      ["Sex", report.sex],
      ["Chest Pain Type", report.chestPainType],
      ["Resting Blood Pressure", report.restingBP],
      ["Cholesterol", report.cholesterol],
      ["Fasting Blood Sugar", report.fastingBS],
      ["Resting ECG", report.restingECG],
      ["Maximum Heart Rate", report.maxHR],
      ["Exercise-Induced Angina", report.exerciseAngina],
      ["Oldpeak", report.oldpeak],
      ["ST Slope", report.stSlope],
    ];

    parameters.forEach(([label, value]) => {
      pdf.text(`${label}: ${value}`, margin, y);
      y += 7;
    });

    y += 8;

    // Prediction
    pdf.setFont("helvetica", "bold");
    pdf.text("AI Prediction", margin, y);

    y += 8;

    pdf.setFont("helvetica", "normal");

    pdf.text(
      `Risk Level: ${report.riskLevel}`,
      margin,
      y,
    );

    y += 7;

    pdf.text(
      `Model Confidence: ${report.modelConfidence.toFixed(1)}%`,
      margin,
      y,
    );

    y += 7;

    pdf.text(
      `Lower Risk Probability: ${(report.class0Probability * 100).toFixed(1)}%`,
      margin,
      y,
    );

    y += 7;

    pdf.text(
      `Higher Risk Probability: ${(report.class1Probability * 100).toFixed(1)}%`,
      margin,
      y,
    );

    y += 15;

    // Prevention
    pdf.setFont("helvetica", "bold");
    pdf.text("What To Do Now", margin, y);

    y += 8;

    pdf.setFont("helvetica", "normal");

    let suggestions: string[] = [];

    if (report.riskLevel === "Higher Risk") {
      suggestions = [
        "Discuss the result with a qualified healthcare professional.",
        "Arrange appropriate medical evaluation based on professional advice.",
        "Follow prescribed medications or treatment plans if applicable.",
        "Monitor relevant cardiovascular health measures regularly.",
        "Maintain a heart-healthy lifestyle and avoid smoking.",
      ];
    } else if (
      report.riskLevel ===
      "Moderate / Borderline Risk"
    ) {
      suggestions = [
        "Consider discussing the result with a healthcare professional.",
        "Maintain regular physical activity appropriate for your health.",
        "Follow a balanced diet with plenty of vegetables and whole foods.",
        "Monitor blood pressure, cholesterol and blood sugar as advised.",
        "Continue regular health check-ups.",
      ];
    } else {
      suggestions = [
        "Continue maintaining a healthy lifestyle.",
        "Stay physically active in a way that is appropriate for you.",
        "Maintain a balanced diet.",
        "Keep up with routine health check-ups.",
        "Monitor cardiovascular risk factors as recommended.",
      ];
    }

    suggestions.forEach((suggestion) => {
      const lines = pdf.splitTextToSize(
        `• ${suggestion}`,
        170,
      );

      pdf.text(lines, margin, y);

      y += lines.length * 6 + 2;
    });

    y += 8;

    pdf.setFontSize(9);
    pdf.setFont("helvetica", "italic");

    pdf.text(
      "This report is generated by CardioPredict-AI and is intended for informational purposes only.",
      margin,
      y,
    );

    pdf.save(
      `CardioPredict-${report.patientName}-${report.id}.pdf`,
    );
  };

  return (
    <div className="bg-[var(--background)] text-[var(--text-primary)]">
      <div className="p-5 sm:p-6 lg:p-8">

        {/* Heading */}
        <div className="mb-8">

          <p className="mb-2 text-sm font-semibold uppercase tracking-wide text-[var(--primary)]">
            Medical Reports
          </p>

          <h1 className="text-3xl font-bold tracking-tight sm:text-4xl">
            Reports
          </h1>

          <p className="mt-2 max-w-2xl text-[var(--text-secondary)]">
            View and download your generated CardioPredict-AI reports.
          </p>

        </div>

        {/* Search */}
        <div className="mb-6">

          <div className="relative">

            <Search
              size={18}
              className="absolute left-4 top-1/2 -translate-y-1/2 text-[var(--text-muted)]"
            />

            <input
              type="text"
              placeholder="Search reports..."
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              className="w-full rounded-lg border border-[var(--border)] bg-[var(--surface)] py-3 pl-11 pr-4 text-sm outline-none transition focus:border-[var(--primary)]"
            />

          </div>

        </div>

        {/* Reports */}
        <section className="overflow-hidden rounded-2xl border border-[var(--border)] bg-[var(--surface)]">

          <div className="border-b border-[var(--border)] p-6">

            <div className="flex items-center gap-3">

              <div className="flex h-10 w-10 items-center justify-center rounded-lg bg-[var(--primary)]/10 text-[var(--primary)]">
                <FileText size={20} />
              </div>

              <div>

                <h2 className="font-semibold">
                  Generated Reports
                </h2>

                <p className="text-sm text-[var(--text-muted)]">
                  {reports.length} reports
                </p>

              </div>

            </div>

          </div>

          {filteredReports.length === 0 ? (

            <div className="px-6 py-16 text-center">

              <div className="mx-auto mb-5 flex h-16 w-16 items-center justify-center rounded-full bg-[var(--background)] text-[var(--text-muted)]">
                <ClipboardList size={28} />
              </div>

              <h3 className="text-lg font-semibold">
                No Reports Available
              </h3>

              <p className="mx-auto mt-2 max-w-md text-sm leading-6 text-[var(--text-secondary)]">
                Reports generated from your AI predictions will appear here.
              </p>

            </div>

          ) : (

            <div className="divide-y divide-[var(--border)]">

              {filteredReports.map((report) => (

                <div
                  key={report.id}
                  className="flex flex-col justify-between gap-4 p-6 transition hover:bg-[var(--background)] sm:flex-row sm:items-center"
                >

                  {/* Report Info */}
                  <div className="flex items-center gap-4">

                    <div className="flex h-11 w-11 items-center justify-center rounded-lg bg-[var(--background)] text-[var(--primary)]">
                      <HeartPulse size={20} />
                    </div>

                    <div>

                      <h3 className="font-semibold">
                        {report.patientName}
                      </h3>

                      <p className="mt-1 text-xs text-[var(--text-muted)]">
                        {report.date} • {report.time}
                      </p>

                    </div>

                  </div>

                  {/* Actions */}
                  <div className="flex items-center gap-4">

                    <span className="text-sm font-medium">
                      {report.riskLevel}
                    </span>

                    <button
                      type="button"
                      onClick={() => generatePDF(report)}
                      className="flex items-center gap-2 rounded-lg border border-[var(--border)] px-4 py-2 text-sm font-medium transition hover:border-[var(--primary)] hover:text-[var(--primary)]"
                    >
                      <Download size={16} />
                      Download
                    </button>

                  </div>

                </div>

              ))}

            </div>

          )}

        </section>

      </div>
    </div>
  );
}

export default Reports;